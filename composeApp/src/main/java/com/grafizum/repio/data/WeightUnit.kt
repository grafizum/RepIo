package com.grafizum.repio.data

import java.util.Locale
import kotlin.math.abs
import kotlin.math.roundToInt

/**
 * The unit a weight is SHOWN and ENTERED in.
 *
 * Storage stays kilograms, exactly like the exercise pool stores canonical
 * English names: a set logged at 40 kg is 40 kg, and switching the unit is a
 * view of it, not a rewrite. Converting the stored rows would round every
 * logged set a second time and make the same set read differently depending on
 * when you looked.
 *
 * The reason this is an enum with functions rather than a boolean is the GRID.
 * A kilogram ladder walks 2.5 kg steps; that is 5.51 lb, and a pound ladder has
 * to walk the pounds a US gym actually stocks — 5 lb on a barbell, 2.5 or 5 lb
 * per hand on a dumbbell. So a value is converted AND snapped to its own
 * increment, per exercise (see [poundGrid]), which is the same rule the
 * kilogram ladders follow.
 */
enum class WeightUnit(val id: String) {
    KG("kg"),
    LBS("lbs");

    /**
     * A stored kilogram weight converted, with NO grid: the honest number for a
     * sum. A session total of 1,234 kg is not a load you set on a bar, so
     * snapping it to the nearest 5 lb would be inventing precision the figure
     * does not have.
     */
    fun fromKg(kg: Double): Double = if (this == KG) kg else kg * LB_PER_KG

    /** The value to show for a stored kilogram weight, on this unit's grid. */
    fun display(kg: Double, kgStep: Double?): Double =
        if (this == KG) kg else snap(fromKg(kg), poundGrid(kgStep))

    /** The kilogram value to store for a number that is in THIS unit. */
    fun toKg(display: Double): Double =
        if (this == KG) display else display / LB_PER_KG

    /**
     * The step a pound ladder walks, taken from the row's own kilogram
     * increment: 1 kg -> 2.5 lb, 2 kg -> 5 lb, 2.5 kg -> 5 lb, 5 kg -> 10 lb.
     * That is the equipment's smallest change in pounds, not a conversion of
     * the number — which is why a 2.5 kg barbell row progresses by 5 lb rather
     * than by 5.51.
     *
     * The candidate nearest the row's own gap wins: 2.5 kg (5.51 lb) takes 5 lb,
     * 2 kg (4.41) takes 5, 1 kg (2.20) takes 2.5, 5 kg (11.02) takes 10.
     *
     * This is the STEP a pound LADDER walks (see `ProgressionEngine.poundLadder`),
     * not a rounding grid for one rung at a time. Rounding a kilogram rung onto
     * a grid is at the mercy of how the kilogram ladder happens to sit — an
     * arnold press stepping 1 kg (2.2 lb) had two levels land on 10 lb — whereas
     * a rung generated by adding one increment cannot repeat at all.
     */
    fun poundGrid(kgStep: Double?): Double {
        val step = kgStep?.takeIf { it > 0.0 } ?: return 2.5
        val gapPounds = step * LB_PER_KG
        return GRID_STEPS_LB.minByOrNull { abs(it - gapPounds) } ?: 2.5
    }

    /** The nearest rung on a pound grid: what a stored weight is shown as. */
    fun snapToGrid(pounds: Double, grid: Double): Double =
        if (grid <= 0.0) pounds else snap(pounds, grid)

    /**
     * True when the pound rung for [aboveKg] is the same rung as [belowKg] — a
     * level-up that would change nothing. Exposed because a test sweeps the
     * whole pool for it: a repeated rung is the one defect this snapping could
     * introduce.
     */
    fun poundsCollide(belowKg: Double, aboveKg: Double, kgStep: Double?): Boolean {
        if (this == KG) return false
        val grid = poundGrid(kgStep)
        return abs(snap(belowKg * LB_PER_KG, grid) - snap(aboveKg * LB_PER_KG, grid)) < 1e-9
    }

    private fun snap(pounds: Double, grid: Double): Double = (pounds / grid).roundToInt() * grid

    companion object {
        /** Exactly 0.45359237 kg by definition, so the conversion is exact, not approximate. */
        const val LB_PER_KG = 2.2046226218487757

        /**
         * The increments a pound ladder can walk, smallest first. 1.25 lb is a
         * real plate (2.5 lb a side on a bar, the smallest adjustable dumbbell
         * step) and 20 lb is the coarsest honest jump for a barbell.
         */
        private val GRID_STEPS_LB = doubleArrayOf(1.25, 2.5, 5.0, 10.0, 20.0)

        /**
         * The countries whose gyms stock pounds. Deliberately a short list: the
         * question is what plates are on the rack, and the US answers it for
         * essentially every user this decides for. Liberia and Myanmar are here
         * because they are the only two other countries that are not metric for
         * mass. The United Kingdom is NOT: it weighs body mass in stones for
         * people and plates in kilograms in gyms, so kilograms is the safer
         * default there and one tap fixes it either way.
         */
        private val POUND_COUNTRIES = setOf("US", "LR", "MM")

        /** The unit named by a stored id, or null when nothing valid is stored. */
        fun fromId(id: String?): WeightUnit? = values().firstOrNull { it.id == id }

        /**
         * The unit the phone's own country uses, for the first run. A unit the
         * user picked themselves always wins — this only decides the default,
         * so a wrong guess is one tap to fix rather than a preference they
         * never knew they had.
         */
        fun defaultFor(locale: Locale): WeightUnit =
            if (locale.country.uppercase(Locale.ROOT) in POUND_COUNTRIES) LBS else KG
    }
}
