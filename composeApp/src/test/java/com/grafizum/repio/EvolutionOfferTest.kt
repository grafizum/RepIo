package com.grafizum.repio

import com.grafizum.repio.data.ExerciseCatalog
import com.grafizum.repio.data.ExerciseProgression
import com.grafizum.repio.data.ProgressionEngine
import com.grafizum.repio.data.ProgressionEntry
import com.grafizum.repio.data.ProgressionEngine.ProgressionState
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * The evolution offer: "what it was" and "what it can become".
 *
 * The owner asked for the post-workout progression window to show the new
 * progression "like an evolution - first show what the exercise was before
 * and then show what it can become". That promise is only worth anything if
 * the two sides carry the SAME numbers the prescriptions come from, so most
 * of what is asserted here is that the popup cannot drift from the engine.
 *
 * The exercises are discovered through the engine rather than named. The
 * catalog is regenerated by the rename pipeline and names are a primary key,
 * so a hardcoded name would fail on the next rename for no reason - what is
 * under test is the offer's arithmetic, not which exercise it happens to be
 * about. Every sweep below therefore runs over EVERY branch in the pool.
 */
class EvolutionOfferTest {

    /** The catalog display name for a progression row. */
    private fun ProgressionEntry.displayName(): String =
        ExerciseCatalog.entryForId(id)?.name ?: slug

    /** Every branch in the pool, paired with its source row. */
    private val branchPairs: List<Pair<ProgressionEntry, String>> =
        ExerciseProgression.ENTRIES.flatMap { entry ->
            entry.branches.map { branch -> entry to branch.entry }
        }

    @Test
    fun thePoolActuallyHasBranchesToOffer() {
        val sources = ExerciseProgression.ENTRIES.filter { it.branches.isNotEmpty() }
        assertTrue(
            "no exercise carries a branch, so every assertion below is vacuous",
            sources.isNotEmpty()
        )
        assertTrue(
            "only ${sources.size} exercises have branches, so the evolution popup " +
                "would have nothing to say for most of the pool",
            sources.size >= 20
        )
    }

    @Test
    fun anOfferIsBuiltForEveryBranchInThePool() {
        assertTrue("no branches to sweep", branchPairs.isNotEmpty())
        branchPairs.forEach { (entry, target) ->
            val sourceName = entry.displayName()
            val targetEntry = ProgressionEngine.entryFor(target)
            assertNotNull("branch target $target has no progression row", targetEntry)

            // The only state the offer is ever shown from: the top of the ladder.
            val state = ProgressionState(ProgressionEngine.effectiveMaxLevel(entry), 1)
            val offer = ProgressionEngine.evolutionOffer(sourceName, target, state)
            assertNotNull("$sourceName -> $target produced no offer, but it is a curated branch", offer)
            assertEquals(target, offer!!.targetName)
            assertEquals(sourceName, offer.from.exerciseName)
        }
    }

    @Test
    fun theBeforeSideIsTheExerciseTheUserHasFinished() {
        val entry = ExerciseProgression.ENTRIES.first { it.branches.isNotEmpty() }
        val name = entry.displayName()
        val max = ProgressionEngine.effectiveMaxLevel(entry)
        val offer = ProgressionEngine.evolutionOffer(
            name, entry.branches.first().entry, ProgressionState(max, 1)
        )!!
        assertEquals(name, offer.from.exerciseName)
        assertEquals(max, offer.from.level)
        assertEquals(max, offer.from.maxLevel)
        // The whole premise of the left-hand card: that track is spent.
        assertEquals(1f, offer.from.progressFraction, 0.0001f)
    }

    @Test
    fun theAfterSideStartsInsideTheTargetsOwnRange() {
        branchPairs.forEach { (entry, target) ->
            val sourceName = entry.displayName()
            val sourceMax = ProgressionEngine.effectiveMaxLevel(entry)
            val offer = ProgressionEngine.evolutionOffer(
                sourceName, target, ProgressionState(sourceMax, 1)
            )!!
            val targetMax = ProgressionEngine.effectiveMaxLevel(ProgressionEngine.entryFor(target)!!)
            assertTrue(
                "$target starts at level ${offer.to.level}, outside 1..$targetMax",
                offer.to.level in 1..targetMax
            )
            assertEquals(targetMax, offer.to.maxLevel)
            assertTrue(
                "${offer.to.exerciseName} bar fraction ${offer.to.progressFraction} is outside 0..1",
                offer.to.progressFraction in 0f..1f
            )
        }
    }

    @Test
    fun aSwapOntoAnEqualLengthLadderDoesNotLandAtItsTop() {
        // The user only ever sees an offer at 100% depth, so the plain
        // relative-depth mapping returns the target's OWN maximum. That is
        // right for a longer ladder (you arrive partway up and keep going)
        // and wrong for an equal-length one: Crunches -> Hanging Knee Raise
        // is 6 levels -> 6 levels, and level 6 of 6 would mean the swap was
        // finished before it started, with two identical bars in the popup.
        var capped = 0
        branchPairs.forEach { (entry, target) ->
            val sourceName = entry.displayName()
            val sourceMax = ProgressionEngine.effectiveMaxLevel(entry)
            val targetEntry = ProgressionEngine.entryFor(target)!!
            val targetMax = ProgressionEngine.effectiveMaxLevel(targetEntry)
            if (targetMax > sourceMax) return@forEach
            val start = ProgressionEngine.branchStartLevel(
                entry, ProgressionState(sourceMax, 1), targetEntry
            )
            assertTrue(
                "$sourceName -> $target lands on level $start of $targetMax, which is " +
                    "already finished - there is nothing left to climb",
                start < targetMax
            )
            capped++
        }
        assertTrue(
            "no equal-length branch was exercised, so the cap is untested",
            capped > 0
        )
    }

    @Test
    fun theTwoSidesNeverLookIdentical() {
        // If both bars read the same the popup is decoration. The "before" is
        // full and the "after" is a fresh track, so they must differ in at
        // least one of level, max level or fill.
        var compared = 0
        branchPairs.forEach { (entry, target) ->
            val offer = ProgressionEngine.evolutionOffer(
                entry.displayName(), target,
                ProgressionState(ProgressionEngine.effectiveMaxLevel(entry), 1)
            )!!
            val differs = offer.from.level != offer.to.level ||
                offer.from.maxLevel != offer.to.maxLevel ||
                offer.from.progressFraction != offer.to.progressFraction
            assertTrue(
                "${offer.from.exerciseName} and ${offer.to.exerciseName} draw the same bar",
                differs
            )
            compared++
        }
        assertTrue("no offers compared", compared > 0)
    }

    @Test
    fun anOfferIsNullForExercisesWithNoRelationship() {
        val entry = ExerciseProgression.ENTRIES.first { it.branches.isNotEmpty() }
        val name = entry.displayName()
        val state = ProgressionState(ProgressionEngine.effectiveMaxLevel(entry), 1)
        // A branch target this source does not actually point at is not an
        // evolution, however similar the two exercises look.
        val stranger = ExerciseProgression.ENTRIES.first {
            it.slug != entry.slug && it.branches.none { b -> b.entry == name }
        }.displayName()
        assertNull(
            ProgressionEngine.evolutionOffer(name, stranger, state)
        )
    }

    @Test
    fun thePreferredBranchIsNeverShorterThanTheSourceWhenOneIsNot() {
        ExerciseProgression.ENTRIES
            // Offerable branches only: [ProgressionEngine.branchesFor] is what the
            // app offers, and an off-movement branch that is longer is not a
            // branch the user can be given (owner, 2026-10-17 — see
            // SameMovementProgressionTest). Measuring the longest branch over the
            // raw list would make this test demand a target the engine must not
            // offer.
            .filter { entry ->
                val offerable = ProgressionEngine.branchesFor(entry)
                offerable.size > 1 && ProgressionEngine.preferredBranch(entry) != null
            }
            .forEach { entry ->
                val preferred = ProgressionEngine.preferredBranch(entry)!!
                val sourceMax = ProgressionEngine.effectiveMaxLevel(entry)
                val longest = ProgressionEngine.branchesFor(entry)
                    .mapNotNull { ProgressionEngine.entryFor(it.entry) }
                    .maxOf { ProgressionEngine.effectiveMaxLevel(it) }
                if (longest < sourceMax) return@forEach
                val chosenMax = ProgressionEngine
                    .entryFor(preferred.entry)
                    ?.let { ProgressionEngine.effectiveMaxLevel(it) } ?: 0
                assertTrue(
                    "preferred branch ${preferred.entry} tops out at $chosenMax, while a " +
                        "branch of ${entry.displayName()} reaches $longest and the source " +
                        "itself is $sourceMax",
                    chosenMax >= sourceMax
                )
            }
    }

    @Test
    fun thePreferredBranchPrefersAdvancedWhenOneIsEligible() {
        var checked = 0
        ExerciseProgression.ENTRIES.forEach { entry ->
            // Offerable branches only, for the same reason as the test above:
            // an "advanced" branch the app would not offer cannot be the one
            // preferredBranch is asked to choose.
            val offerable = ProgressionEngine.branchesFor(entry)
            if (offerable.none { it.tag == "advanced" }) return@forEach
            val sourceMax = ProgressionEngine.effectiveMaxLevel(entry)
            val advancedIsEligible = offerable.any { branch ->
                branch.tag == "advanced" &&
                    ProgressionEngine.entryFor(branch.entry)
                        ?.let { ProgressionEngine.effectiveMaxLevel(it) >= sourceMax } == true
            }
            if (!advancedIsEligible) return@forEach
            assertEquals(
                "an eligible advanced branch exists for ${entry.displayName()} " +
                    "but preferredBranch did not choose it",
                "advanced",
                ProgressionEngine.preferredBranch(entry)!!.tag
            )
            checked++
        }
        assertTrue("no exercise had an eligible advanced branch", checked > 0)
    }
}
