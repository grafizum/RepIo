#!/usr/bin/env python3
"""Emit the Kotlin catalog + progression tables from the v5 pipeline output.

Generates:
  * composeApp/src/main/java/com/grafizum/repio/data/ExerciseCatalog.kt
    (generated — do not hand-edit; run the pipeline instead)
  * composeApp/src/main/java/com/grafizum/repio/data/ExerciseProgression.kt
    (generated — the per-exercise progression payload the engine reads; all
    JSON sequences are pre-parsed here into Kotlin lists so the app needs no
    JSON parser at runtime)
  * rewrites composeApp/src/main/java/com/grafizum/repio/ui/components/
    ExerciseDescriptions.kt as a thin delegate onto the catalog

Run from the repository root:
    python tools/exercise-db/build_progression.py && python tools/exercise-db/emit_progression_kotlin.py
"""

from __future__ import annotations

import hashlib
import json
import pathlib
import re

import generalize

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = pathlib.Path(__file__).resolve().parent / "out"
MAIN = ROOT / "composeApp/src/main/java/com/grafizum/repio"

CATALOG = OUT / "catalog_v5.json"
RENAMES = OUT / "name_renames.json"
PROGRESSION = OUT / "progression_v5.json"

STAGE_ORDER = ["I", "II", "III", "IV", "V", "VI", "VII", "VIII", "IX", "X", "XI", "XII", "XIII"]

HEADER = """// GENERATED by tools/exercise-db/emit_progression_kotlin.py from tools/exercise-db/out/catalog_v5.json.
// Do not edit by hand — edit tools/exercise-db/build_progression.py (or the source CSV) and re-run:
//   python tools/exercise-db/build_progression.py && python tools/exercise-db/emit_progression_kotlin.py

package com.grafizum.repio.data

"""


def kstring(value: str) -> str:
    """Escape a Python string as a Kotlin string literal."""
    out = (value or "").replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\\$")
    out = out.replace("\r", " ").replace("\n", " ")
    return f"\"{out}\""


def kdouble(value) -> str:
    if value is None:
        return "null"
    return f"{float(value)}"


def kint(value) -> str:
    return "null" if value is None else str(int(value))


def kbool(value: bool) -> str:
    return "true" if value else "false"


def kintlist(values) -> str:
    if not values:
        return "emptyList()"
    return "listOf(" + ", ".join(str(int(v)) for v in values) + ")"


def kdoublelist(values) -> str:
    if not values:
        return "emptyList()"
    return "listOf(" + ", ".join(f"{float(v)}" for v in values) + ")"


def kstringlist(values) -> str:
    if not values:
        return "emptyList()"
    return "listOf(" + ", ".join(kstring(v) for v in values) + ")"


def kbranch_list(branches) -> str:
    """Emit a List<ProgressionBranch> from the pipeline's branch dicts."""
    if not branches:
        return "emptyList()"
    items = []
    for b in branches:
        items.append(
            "ProgressionBranch("
            + f"entry = {kstring(b['entry'])}, "
            + f"entrySlug = {kstring(b['entrySlug'])}, "
            + f"nodes = {kstringlist(b['nodes'])}, "
            + f"note = {kstring(b['note'])}, "
            + f"tag = {kstring(b['tag'])})"
        )
    return "listOf(" + ",\n                ".join(items) + ")"


def kceiling(ceiling) -> str:
    """Emit a nullable HumanCeiling from the pipeline's ceiling dict."""
    if not ceiling:
        return "null"
    return (
        "HumanCeiling("
        + f"load = {kdouble(ceiling['load'])}, "
        + f"femaleLoad = {kdouble(ceiling.get('femaleLoad'))}, "
        + f"basis = {kstring(ceiling['basis'])})"
    )


def parse_reps(json_str: str) -> list[int] | None:
    if not json_str or not json_str.strip():
        return None
    try:
        data = json.loads(json_str)
        return [int(x) for x in data]
    except (json.JSONDecodeError, TypeError, ValueError):
        return None


def parse_roman(json_str: str) -> list[list[int]]:
    """The stage->reps table as a list indexed by stage-1 (I=0)."""
    if not json_str or not json_str.strip():
        return []
    try:
        data = json.loads(json_str)
    except json.JSONDecodeError:
        return []
    order = ["I", "II", "III", "IV", "V", "VI", "VII", "VIII", "IX", "X", "XI", "XII", "XIII"]
    out = []
    for stage in order:
        reps = data.get(stage)
        out.append([int(x) for x in reps] if reps else [])
    return out


def parse_variations(json_str: str) -> list[str]:
    """A variation ladder JSON (level -> variation name) as a flat per-level list.

    Accepts both emitted shapes: a top-level list of ladder items and the
    wrapped `{"ladder": [...]}` object the CSV uses.
    """
    if not json_str or not json_str.strip():
        return []
    try:
        data = json.loads(json_str)
        if isinstance(data, dict):
            data = data.get("ladder", [])
        return [str(item["variation"]) for item in data]
    except (json.JSONDecodeError, TypeError, KeyError, ValueError):
        return []


def parse_level_values(json_str: str) -> list[float]:
    if not json_str or not json_str.strip():
        return []
    try:
        data = json.loads(json_str)
        return [float(item["value"]) for item in data]
    except (json.JSONDecodeError, TypeError, KeyError, ValueError):
        return []


# Populated in main() before the emission loops run.
ROMAN_CONST_NAMES: dict[str, str] = {}
LADDER_CONST_NAMES: dict[str, str] = {}


def roman_table_const(json_str: str) -> str | None:
    """The Kotlin constant name for a Roman pattern, deduped across the pool.

    The 601 rows share only a handful of distinct patterns (standard_3x8-12_v1
    alone covers 430); emitting the table inline per row blows the JVM's 64KB
    <clinit> limit, so the emitter dedupes them into named constants.
    """
    table = parse_roman(json_str)
    if not table or all(not s for s in table):
        return None
    return ROMAN_CONST_NAMES.get(json_str or "")


def roman_const_ref(json_str: str) -> str:
    """A Kotlin expression referencing the row's deduped Roman table constant."""
    name = ROMAN_CONST_NAMES.get(json_str or "")
    return f"ProgressionTables.{name}" if name else "emptyList()"


def ladder_const_ref(json_str: str) -> str:
    """A Kotlin expression referencing the row's deduped ladder constant."""
    name = LADDER_CONST_NAMES.get(json_str or "")
    return f"ProgressionTables.{name}" if name else "emptyList()"


def main() -> int:
    entries = json.loads(CATALOG.read_text(encoding="utf-8"))
    prog = json.loads(PROGRESSION.read_text(encoding="utf-8"))
    renames = json.loads(RENAMES.read_text(encoding="utf-8")) if RENAMES.is_file() else {}
    entries.sort(key=lambda r: r["name"].lower())
    prog_by_id = {p["id"]: p for p in prog}

    # Dedupe the Roman tables and level ladders into named constants: only a
    # handful of distinct values exist across the whole pool, and inlining all
    # of them per row overflows the JVM <clinit> method-size limit.
    roman_values = []
    ladder_values = []
    for d in prog:
        table = parse_roman(d["romanPattern"])
        if any(table):
            roman_values.append((d["romanPattern"], table))
        ladder = parse_level_values(d["levelValueSequence"])
        if ladder:
            ladder_values.append((d["levelValueSequence"], ladder))

    global ROMAN_CONST_NAMES, LADDER_CONST_NAMES
    ROMAN_CONST_NAMES = {}
    seen_tables = {}
    for raw, table in roman_values:
        if raw in seen_tables:
            continue
        try:
            pid = json.loads(raw).get("_id", "")
        except json.JSONDecodeError:
            pid = ""
        # Stable name: the roman_pattern_id when present, else a short hash.
        import hashlib
        h = hashlib.md5(raw.encode()).hexdigest()[:6]
        name = "ROMAN_" + re.sub(r"[^A-Za-z0-9]", "_", str(pid)).upper().strip("_")
        if not pid:
            name = "ROMAN_PAT_" + h
        if name in seen_tables.values():
            name = name + "_" + h
        seen_tables[raw] = name
    ROMAN_CONST_NAMES = seen_tables

    LADDER_CONST_NAMES = {}
    seen_ladders = {}
    for raw, ladder in ladder_values:
        if raw in seen_ladders:
            continue
        import hashlib
        h = hashlib.md5(raw.encode()).hexdigest()[:6]
        seen_ladders[raw] = "LADDER_" + h
    LADDER_CONST_NAMES = seen_ladders

    # ------------------------------------------------------------------
    # ExerciseCatalog.kt
    # ------------------------------------------------------------------
    lines = [
        HEADER.rstrip("\n"),
        "",
        "/**",
        " * One exercise of the built-in pool, rebuilt from the v5 progression",
        " * database (exercise_progression_database_v5.csv).",
        " *",
        " * The pool is data now: names, primary muscle, equipment category and the",
        " * English method description all come from the CSV pipeline (descriptions",
        " * are merged from the previous catalog where names reconciled, then from",
        " * tools/exercise-db/data/hand_descriptions.py for the rest).",
        " * The progression payload for every entry lives in [ExerciseProgression].",
        " */",
        "data class ExerciseCatalogEntry(",
        "    val id: String,         // v5 normalized_exercise_id (stable join key)",
        "    val name: String,",
        "    val muscle: String,     // precise primary muscle (join key for badges/analytics)",
        "    val equipment: String,  // one of [ExerciseCatalog.CATEGORIES]",
        "    val type: String,       // training category (strength_weighted_or_machine, …)",
        "    val level: String,      // mechanic (compound / isolation)",
        "    val description: String // English method text (old catalog or hand-written)",
        ")",
        "",
        "object ExerciseCatalog {",
        "",
        "    /** The equipment categories the pool uses (plus \"All\" in the UI). */",
        "    val CATEGORIES = listOf(",
        "        \"Bodyweight\", \"Barbell\", \"Dumbbell\", \"Kettlebell\",",
        "        \"Cable\", \"Machine\", \"Bands\", \"Other\",",
        "    )",
        "",
        "    val ENTRIES = listOf(",
    ]
    for r in entries:
        lines.append(
            f"        ExerciseCatalogEntry({kstring(r['id'])}, {kstring(r['name'])}, {kstring(r['muscle'])}, "
            f"{kstring(r['equipment'])}, {kstring(r['type'])}, {kstring(r['level'])}, "
            f"{kstring(r['description'])}),"
        )
    lines += [
        "    )",
        "",
        "    /** Pool names, sorted — the canonical list the pickers and search use. */",
        "    val NAMES = ENTRIES.map { it.name }.sorted()",
        "",
        "    private val byName = ENTRIES.associateBy { it.name.lowercase() }",
        "    private val byId = ENTRIES.associateBy { it.id }",
        "",
        "    /** The catalog entry for a pool exercise (case-insensitive), or null for custom ones. */",
        "    fun entryFor(name: String): ExerciseCatalogEntry? = byName[name.trim().lowercase()]",
        "",
        "    /** The catalog entry for a v5 id, or null. */",
        "    fun entryForId(id: String): ExerciseCatalogEntry? = byId[id]",
        "",
        "    /** The precise primary muscle of a pool exercise, or \"\" outside the pool. */",
        "    fun muscleFor(name: String): String = entryFor(name)?.muscle ?: \"\"",
        "",
        "    /** The equipment category of a pool exercise, or \"\" outside the pool. */",
        "    fun equipmentFor(name: String): String = entryFor(name)?.equipment ?: \"\"",
        "",
        "    /** The English method description of a pool exercise, or null outside it. */",
        "    fun descriptionFor(name: String): String? = entryFor(name)?.description?.ifBlank { null }",
        "",
        "    /**",
        "     * True when the row is a mobility or stretching movement.",
        "     *",
        "     * It reads the row's own TRAINING CATEGORY rather than its name: \"Sphinx Pose\" and",
        "     * \"Bear Crawl\" say nothing about whether they are a stretch, and the generator's",
        "     * own audit counts those rows by this (see docs/program-quality-audit.md).",
        "     *",
        "     * EMITTED HERE RATHER THAN HAND-WRITTEN. The first version of this helper was",
        "     * appended to the generated file by hand, and the next pipeline run silently",
        "     * deleted it - the emitter owns every line of this file, so anything the rest of",
        "     * the app calls has to be emitted with it.",
        "     */",
        "    fun isMobilityRow(name: String): Boolean =",
        "        entryFor(name)?.type == MOBILITY_TYPE",
        "",
        "    /** The training category of every stretch and pose in the pool. */",
        "    const val MOBILITY_TYPE = \"mobility_stretching\"",
        "",
        generalize.format_rename_table(renames).rstrip("\n"),
        "}",
        "",
    ]
    catalog_target = MAIN / "data/ExerciseCatalog.kt"
    catalog_target.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {catalog_target.relative_to(ROOT)} ({len(entries)} entries)")

    # ------------------------------------------------------------------
    # ExerciseProgression.kt — all JSON pre-parsed into Kotlin lists.
    # ------------------------------------------------------------------
    # Roman-table and ladder constants (deduped across the pool).
    const_lines = [
        HEADER.rstrip("\n"),
        "",
        "/**",
        " * Shared progression tables, deduped by the pipeline: the 601 rows use",
        " * only a handful of distinct Roman patterns and level ladders, so they",
        " * emit as named constants instead of one copy per row.",
        " */",
        "internal object ProgressionTables {",
        "",
        "    /** A Roman pattern: index 0 = stage I, each row is that stage's per-set reps. */",
        "    val EMPTY_STAGE = emptyList<Int>()",
        "",
    ]
    for raw, name in sorted(ROMAN_CONST_NAMES.items(), key=lambda kv: kv[1]):
        table = parse_roman(raw)
        const_lines.append(
            f"    val {name}: List<List<Int>> = listOf({', '.join(kintlist(s) for s in table)})"
        )
    const_lines.append("")
    const_lines.append("    /** An explicit level -> load ladder: index 0 = level 1. */")
    for raw, name in sorted(LADDER_CONST_NAMES.items(), key=lambda kv: kv[1]):
        ladder = parse_level_values(raw)
        const_lines.append(f"    val {name}: List<Double> = listOf({', '.join(f'{v}' for v in ladder)})")
    const_lines += ["", "}", ""]

    tables_target = MAIN / "data/ProgressionTables.kt"
    tables_target.write_text("\n".join(const_lines), encoding="utf-8")
    print(f"wrote {tables_target.relative_to(ROOT)} "
          f"({len(ROMAN_CONST_NAMES)} roman, {len(LADDER_CONST_NAMES)} ladder constants)")

    # The data class itself.
    cls = [
        HEADER.rstrip("\n"),
        "",
        "/**",
        " * The progression payload for one v5 row, with every JSON sequence already",
        " * parsed by the pipeline. Internal representation — the UI never renders",
        " * these fields directly; it goes through [ProgressionEngine], which turns",
        " * them into starting prescriptions and level/stage decisions.",
        " */",
        "data class ProgressionEntry(",
        "    val id: String,",
        "    val slug: String,",
        "    val method: String,",
        "    val valueSource: String,",
        "    val unit: String,",
        "    /** Load at level 1 (also the base of the linear fallback ladder). */",
        "    val level1: Double?,",
        "    val increment: Double?,",
        "    val maxLevel: Int?,",
        "    val minValue: Double?,",
        "    val maxValue: Double?,",
        "    val step: Double?,",
        "    val repMin: Int?,",
        "    val repMax: Int?,",
        "    val restSeconds: Int?,",
        "    val defaultSetCount: Int?,",
        "    /** Easy/Medium/Hard starting levels (main level, 1-based). */",
        "    val easyLevel: Int?, val mediumLevel: Int?, val hardLevel: Int?,",
        "    /** Easy/Medium/Hard starting loads in [unit]. */",
        "    val easyValue: Double?, val mediumValue: Double?, val hardValue: Double?,",
        "    /** Easy/Medium/Hard start stage indexes (1 = I, 13 = XIII). */",
        "    val easyStage: Int, val mediumStage: Int, val hardStage: Int,",
        "    /** Easy/Medium/Hard per-set target reps at the start stage. */",
        "    val easyReps: List<Int>, val mediumReps: List<Int>, val hardReps: List<Int>,",
        "    /** The Roman pattern as a stage-indexed table: index 0 = stage I. */",
        "    val romanStages: List<List<Int>>,",
        "    val resetPolicy: String,",
        "    /** Stage index (1-based) to reset to after a jump, per the CSV. */",
        "    val resetStageAfterJump: Int,",
        "    val preJumpReps: List<Int>,",
        "    val postJumpReps: List<Int>,",
        "    /** Explicit level -> load ladder (index 0 = level 1). */",
        "    val levelValues: List<Double>,",
        "    /** Variation ladder pre-parsed from the CSV (index 0 = level 1); empty when the method has none. */",
        "    val variations: List<String>,",
        "    val isBeginnerFriendly: Boolean,",
        "    val isSimpleAppReady: Boolean,",
        "    val requiresCoachReview: Boolean,",
        "    val includeInStrengthV1: Boolean,",
        "    val includeInCardioV1: Boolean,",
        "    val includeInMobilityV1: Boolean,",
    "    val beginnerBuildEligible: Boolean,",
    "    val validationStatus: String,",
    "    /** Coach-curated alternative paths (empty = none). */",
    "    val branches: List<ProgressionBranch>,",
    "    /** Realistic human ceiling, null when the exercise has no load cap. */",
    "    val ceiling: HumanCeiling?",
    ")",
    "",
    "/**",
    " * One alternative progression path offered when an exercise is mastered.",
    " * [entry] is the exercise the user switches to, [nodes] its future path",
    " * (mini progress track on the mastery card), [note] the one-line coach",
    " * text, and [tag] is either new or advanced.",
    " */",
    "data class ProgressionBranch(",
    "    val entry: String,",
    "    val entrySlug: String,",
    "    val nodes: List<String>,",
    "    val note: String,",
    "    val tag: String,",
    ")",
    "",
    "/**",
    " * The realistic healthy human ceiling of an exercise. [load] is in the",
    " * row's own unit (null for bodyweight skills whose ceiling is the skill",
    " * itself), [femaleLoad] when elite norms separate it, [basis] names the",
    " * source the figure comes from.",
    " */",
    "data class HumanCeiling(",
    "    val load: Double?,",
    "    val femaleLoad: Double?,",
    "    val basis: String,",
    ")",
        "",
    ]
    # The constructor lines, sharded across chunk objects: 601 constructor
    # calls in ONE listOf() overflow the JVM <clinit> method-size limit even
    # with the tables deduped, so the list is assembled from chunks of 150.
    entry_lines = []
    emitted = 0
    for r in entries:
        d = prog_by_id.get(r["id"])
        if d is None:
            continue
        stage_index = lambda name: (STAGE_ORDER.index(name) + 1
                                    if name in STAGE_ORDER else 1)
        entry_lines.append(
            f"        ProgressionEntry({kstring(d['id'])}, {kstring(d['slug'])}, {kstring(d['method'])}, "
            f"{kstring(d['valueSource'])}, {kstring(d['unit'])}, "
            f"{kdouble(d['level1'])}, {kdouble(d['increment'])}, {kint(d['maxLevel'])}, "
            f"{kdouble(d['minValue'])}, {kdouble(d['maxValue'])}, {kdouble(d['step'])}, "
            f"{kint(d['repMin'])}, {kint(d['repMax'])}, {kint(d['restSeconds'])}, {kint(d['defaultSetCount'])}, "
            f"{kint(d['easy']['level'])}, {kint(d['medium']['level'])}, {kint(d['hard']['level'])}, "
            f"{kdouble(d['easy']['value'])}, {kdouble(d['medium']['value'])}, {kdouble(d['hard']['value'])}, "
            f"{stage_index(d['easy']['stage'])}, {stage_index(d['medium']['stage'])}, {stage_index(d['hard']['stage'])}, "
            f"{kintlist(parse_reps(d['easy']['reps']) or [])}, {kintlist(parse_reps(d['medium']['reps']) or [])}, "
            f"{kintlist(parse_reps(d['hard']['reps']) or [])}, "
            f"{roman_const_ref(d['romanPattern'])}, "
            f"{kstring(d['resetPolicy'])}, {stage_index(d['resetStageAfterJump'])}, "
            f"{kintlist(parse_reps(d['preJumpReps']) or [])}, {kintlist(parse_reps(d['postJumpReps']) or [])}, "
            f"{ladder_const_ref(d['levelValueSequence'])}, "
            f"{kstringlist(parse_variations(d['variationSequence']))}, "
            f"{kbool(d['isBeginnerFriendly'])}, {kbool(d['isSimpleAppReady'])}, {kbool(d['requiresCoachReview'])}, "
            f"{kbool(d['includeInStrengthV1'])}, {kbool(d['includeInCardioV1'])}, {kbool(d['includeInMobilityV1'])}, "
            f"{kbool(d['beginnerBuildEligible'])}, {kstring(d['validationStatus'])}, "
            f"{kbranch_list(d.get('branches'))}, "
            f"{kceiling(d.get('ceiling'))}),"
        )
        emitted += 1

    CHUNK = 50
    chunks = [entry_lines[i:i + CHUNK] for i in range(0, len(entry_lines), CHUNK)]
    # Each chunk lives in its OWN object: Kotlin compiles every property
    # initializer of an object into that object's single <clinit>, so chunks
    # sharing ExerciseProgression would still overflow the method-size limit.
    p = cls + [
        "",
        "object ExerciseProgression {",
        "",
    ]
    for ci, chunk in enumerate(chunks):
        p += [
            f"    private object Chunk{ci} {{",
            f"        val ROWS: List<ProgressionEntry> = listOf(",
        ]
        p += ["            " + line.strip() for line in chunk]
        p += ["        )", "        }", ""]
    chunk_refs = ", ".join(f"Chunk{ci}.ROWS" for ci in range(len(chunks)))
    p += [
        f"    val ENTRIES: List<ProgressionEntry> = listOf({chunk_refs}).flatten()",
        "",
        "    private val byId = ENTRIES.associateBy { it.id }",
        "",
        "    /** The progression payload for a pool exercise name (case-insensitive), or null. */",
        "    fun forName(name: String): ProgressionEntry? =",
        "        ExerciseCatalog.entryFor(name)?.let { byId[it.id] }",
        "",
        "    /** The progression payload keyed by the catalog entry's id. */",
        "    fun forId(id: String): ProgressionEntry? = byId[id]",
        "}",
        "",
    ]
    prog_target = MAIN / "data/ExerciseProgression.kt"
    prog_target.write_text("\n".join(p), encoding="utf-8")
    print(f"wrote {prog_target.relative_to(ROOT)} ({emitted} entries)")

    # ------------------------------------------------------------------
    # ExerciseDescriptions.kt stays a delegate — the descriptions live in
    # the catalog now, and a second copy would drift.
    # ------------------------------------------------------------------
    desc = "\n".join([
        "package com.grafizum.repio.ui.components",
        "",
        "import com.grafizum.repio.data.ExerciseCatalog",
        "",
        "/**",
        " * Returns the method description for a built-in exercise, or null when unknown.",
        " *",
        " * The texts live in the generated [ExerciseCatalog] (rebuilt from the v5",
        " * progression database); this delegate keeps the historical call sites stable.",
        " */",
        "fun getExerciseDescription(name: String): String? =",
        "    ExerciseCatalog.descriptionFor(name)",
        "",
    ])
    desc_target = MAIN / "ui/components/ExerciseDescriptions.kt"
    desc_target.write_text(desc, encoding="utf-8")
    print(f"rewrote {desc_target.relative_to(ROOT)} as a catalog delegate")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
