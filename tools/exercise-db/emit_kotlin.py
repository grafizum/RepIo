#!/usr/bin/env python3
"""Emit the Kotlin exercise catalog from out/catalog.json.

Generates:
  * composeApp/src/main/java/com/grafizum/repio/data/ExerciseCatalog.kt
    (generated — do not hand-edit; run this script instead)
  * rewrites composeApp/src/main/java/com/grafizum/repio/ui/components/
    ExerciseDescriptions.kt as a thin delegate onto the catalog

Run from the repository root:
    python tools/exercise-db/emit_kotlin.py
"""

from __future__ import annotations

import json
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import mapping as M

ROOT = pathlib.Path(__file__).resolve().parents[2]
CATALOG = pathlib.Path(__file__).resolve().parent / "out/catalog.json"
MAIN = ROOT / "composeApp/src/main/java/com/grafizum/repio"

HEADER = """// GENERATED by tools/exercise-db/emit_kotlin.py from tools/exercise-db/out/catalog.json.
// Do not edit by hand — edit the CSV/mapping and re-run the pipeline:
//   python tools/exercise-db/build.py && python tools/exercise-db/emit_kotlin.py

package com.grafizum.repio.data

"""


def kstring(value: str) -> str:
    """Escape a Python string as a Kotlin string literal."""
    out = value.replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\\$")
    return f"\"{out}\""


def main() -> int:
    entries = json.loads(CATALOG.read_text(encoding="utf-8"))
    entries.sort(key=lambda r: r["name"].lower())

    lines = [
        HEADER.rstrip("\n"),
        "",
        "/**",
        " * One exercise of the built-in pool, rebuilt from the megaGymDataset.",
        " *",
        " * The pool is data now: names, primary muscle, equipment category, movement",
        " * type, difficulty and the English method description all come from the CSV",
        " * pipeline. The curated hand-written pool this replaces is on main; this",
        " * branch is an experiment and can be reverted wholesale.",
        " */",
        "data class ExerciseCatalogEntry(",
        "    val name: String,",
        "    val muscle: String,     // precise primary muscle (join key for badges/analytics)",
        "    val equipment: String,  // one of [ExerciseCatalog.CATEGORIES]",
        "    val type: String,       // Strength / Stretching / Plyometrics / Cardio / …",
        "    val level: String,      // Beginner / Intermediate / Expert",
        "    val description: String // English method text, may be blank",
        ")",
        "",
        "object ExerciseCatalog {",
        "",
        "    /** The equipment categories the rebuilt pool uses (plus \"All\" in the UI). */",
        "    val CATEGORIES = listOf(",
    ]
    for cat in M.NEW_EQUIPMENT_CATEGORIES:
        lines.append(f"        {kstring(cat)},")
    lines += [
        "    )",
        "",
        "    val ENTRIES = listOf(",
    ]
    for r in entries:
        lines.append(
            f"        ExerciseCatalogEntry({kstring(r['name'])}, {kstring(r['muscle'])}, "
            f"{kstring(r['equipment'])}, {kstring(r['type'])}, {kstring(r['level'])}, "
            f"{kstring(r['description'])}),"
        )
    lines += [
        "    )",
        "",
        "    /** Pool names, sorted — the canonical list the pickers and search use. */",
        "    val NAMES = ENTRIES.map { it.name }.sorted()",
        "",
        "    private val byName = ENTRIES.associateBy { it.name.lowercase() }",
        "",
        "    /** The catalog entry for a pool exercise (case-insensitive), or null for custom ones. */",
        "    fun entryFor(name: String): ExerciseCatalogEntry? = byName[name.trim().lowercase()]",
        "",
        "    /** The precise primary muscle of a pool exercise, or \"\" outside the pool. */",
        "    fun muscleFor(name: String): String = entryFor(name)?.muscle ?: \"\"",
        "",
        "    /** The equipment category of a pool exercise, or \"\" outside the pool. */",
        "    fun equipmentFor(name: String): String = entryFor(name)?.equipment ?: \"\"",
        "",
        "    /** The English method description of a pool exercise, or null outside it. */",
        "    fun descriptionFor(name: String): String? = entryFor(name)?.description?.ifBlank { null }",
        "}",
        "",
    ]
    target = MAIN / "data/ExerciseCatalog.kt"
    target.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {target.relative_to(ROOT)} ({len(entries)} entries)")

    # ExerciseDescriptions.kt becomes a delegate — the descriptions live in the
    # catalog now, and a second copy would drift.
    desc = "\n".join([
        "package com.grafizum.repio.ui.components",
        "",
        "import com.grafizum.repio.data.ExerciseCatalog",
        "",
        "/**",
        " * Returns the method description for a built-in exercise, or null when unknown.",
        " *",
        " * The texts live in the generated [ExerciseCatalog] (rebuilt from the",
        " * exercise-database CSV); this delegate keeps the historical call sites stable.",
        " */",
        "fun getExerciseDescription(name: String): String? =",
        "    ExerciseCatalog.descriptionFor(name)",
        "",
    ])
    desc_target = MAIN / "ui/components/ExerciseDescriptions.kt"
    desc_target.write_text(desc, encoding="utf-8")
    print(f"rewrote {desc_target.relative_to(ROOT)} as a catalog delegate")
    return 0


if __name__ == "__main__":
    sys.exit(main())
